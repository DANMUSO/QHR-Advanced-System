<?php

namespace App\Modules\Documents\Http\Controllers;

use App\Http\Controllers\Controller;
use App\Models\Employee;
use App\Modules\Documents\Models\DocumentType;
use App\Modules\Documents\Models\EmployeeDocument;
use App\Modules\Documents\Models\EmployeeDocumentVersion;
use App\Modules\Documents\Notifications\DocumentAddedToFile;
use App\Modules\Documents\Support\DocumentAccess;
use App\Modules\Employees\Models\EmployeeLetter;
use App\Modules\Employees\Services\LetterService;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\Rule;
use Symfony\Component\HttpFoundation\StreamedResponse;

/** Employee personal file: list, upload, replace (versioned), edit, delete, download. */
class EmployeeDocumentController extends Controller
{
    /** The signed-in user's own file. */
    public function mine(Request $request): JsonResponse
    {
        $employee = $request->user()->employee;
        abort_unless($employee, 404, 'Your account is not linked to an employee record.');

        return $this->index($request, $employee);
    }

    /** Self-service upload to own file. */
    public function storeMine(Request $request): JsonResponse
    {
        $employee = $request->user()->employee;
        abort_unless($employee, 404, 'Your account is not linked to an employee record.');

        return $this->store($request, $employee);
    }

    public function index(Request $request, Employee $employee): JsonResponse
    {
        $user = $request->user();
        $manages = DocumentAccess::manages($user);
        abort_unless($manages || DocumentAccess::isOwner($user, $employee), 403);

        // Include files from earlier employment periods. Confidential files recorded by another company
        // (e.g. warnings before a transfer) stay with that company.
        $lineage = DocumentAccess::lineage($employee);
        $otherCompany = array_keys(array_filter($lineage, fn ($companyId) => $companyId !== (int) $employee->company_id));
        $documents = EmployeeDocument::query()
            ->withoutGlobalScope('company')
            ->whereIn('employee_id', array_keys($lineage))
            ->when(! $manages, fn ($q) => $q->where('is_confidential', false))
            ->when($otherCompany, fn ($q) => $q->where(fn ($w) => $w->whereNotIn('employee_id', $otherCompany)->orWhere('is_confidential', false)))
            ->with(['type:id,name,group', 'uploader:id,name'])
            ->withCount('versions')
            ->orderByDesc('created_at')
            ->get()
            ->map(fn (EmployeeDocument $d) => $this->present($d, $user));

        return response()->json([
            'employee' => ['id' => $employee->id, 'full_name' => $employee->full_name, 'employee_number' => $employee->employee_number],
            'documents' => $documents,
            // Letters generated by HR (confirmation, employment, ...) belong to the personal file too.
            'letters' => class_exists(EmployeeLetter::class) ? EmployeeLetter::withoutGlobalScopes()->whereIn('employee_id', array_keys($lineage))
                ->latest('id')->get()->map(fn (EmployeeLetter $l) => [
                    'id' => $l->id, 'reference' => $l->reference, 'subject' => $l->subject,
                    'template_name' => LetterService::TEMPLATES[$l->template][0] ?? $l->template,
                    'issued_at' => $l->created_at, 'path' => '/api/employees/letters/'.$l->id.'/download',
                ])->values() : [],
            'checklist' => $this->checklist($employee, $manages),
            'can_manage' => $manages,
            'max_upload_kb' => $manages ? DocumentAccess::HR_MAX_KB : DocumentAccess::SELF_MAX_KB,
        ]);
    }

    public function store(Request $request, Employee $employee): JsonResponse
    {
        $user = $request->user();
        $manages = DocumentAccess::manages($user);
        $isOwner = DocumentAccess::isOwner($user, $employee);
        abort_unless($manages || $isOwner, 403);

        $data = $this->validated($request, $employee, true, $manages);
        $type = isset($data['document_type_id']) ? DocumentType::withoutGlobalScope('company')->find($data['document_type_id']) : null;
        if (! $manages && $type && ! $type->allow_self_upload) {
            abort(422, "Only HR can upload {$type->name} documents.");
        }

        $file = DocumentAccess::store($request->file('file'), "documents/employees/{$employee->id}");
        $document = new EmployeeDocument([
            ...collect($data)->except('file')->all(),
            ...$file,
            'company_id' => $employee->company_id,
            'employee_id' => $employee->id,
            // Owners upload as "Self"; HR uploads to anyone's file (including their own, if they ask) as "HR Admin".
            'source' => $isOwner && ! ($manages && $request->input('source') === 'hr') ? 'self' : 'hr',
            'is_confidential' => $manages && $request->boolean('is_confidential'),
            'uploaded_by' => $user->id,
            'version' => 1,
        ]);
        $document->save();

        if (! $isOwner && ! $document->is_confidential && $employee->user) {
            $employee->user->notify(new DocumentAddedToFile($document));
        }

        return response()->json($this->present($document->load(['type:id,name,group', 'uploader:id,name']), $user), 201);
    }

    public function show(Request $request, EmployeeDocument $employeeDocument): JsonResponse
    {
        $user = $request->user();
        abort_unless(DocumentAccess::canView($user, $employeeDocument), 403);
        $employeeDocument->load(['type:id,name,group', 'uploader:id,name', 'versions.uploader:id,name', 'employee:id,first_name,last_name']);

        return response()->json([
            ...$this->present($employeeDocument, $user),
            'versions' => $employeeDocument->versions->map(fn ($v) => [
                'id' => $v->id, 'version' => $v->version, 'file_name' => $v->file_name, 'mime_type' => $v->mime_type,
                'file_size' => $v->file_size, 'size_human' => DocumentAccess::humanSize((int) $v->file_size),
                'uploaded_by' => $v->uploader?->name, 'uploaded_at' => $v->uploaded_at,
            ]),
        ]);
    }

    public function update(Request $request, EmployeeDocument $employeeDocument): JsonResponse
    {
        $user = $request->user();
        abort_unless(DocumentAccess::canModify($user, $employeeDocument), 403);
        $manages = DocumentAccess::manages($user);
        $data = $this->validated($request, $employeeDocument->employee, false, $manages);
        if ($manages && $request->has('is_confidential')) {
            $data['is_confidential'] = $request->boolean('is_confidential');
        }
        if (array_key_exists('expiry_date', $data) && (string) $data['expiry_date'] !== (string) $employeeDocument->expiry_date?->toDateString()) {
            $data['alert_30_sent_at'] = null;
            $data['alert_7_sent_at'] = null;
        }
        $employeeDocument->update($data);

        return response()->json($this->present($employeeDocument->fresh(['type:id,name,group', 'uploader:id,name']), $user));
    }

    /** Uploads a new file for the document; the previous file is kept as a version. */
    public function replace(Request $request, EmployeeDocument $employeeDocument): JsonResponse
    {
        $user = $request->user();
        abort_unless(DocumentAccess::canModify($user, $employeeDocument), 403);
        $max = DocumentAccess::manages($user) ? DocumentAccess::HR_MAX_KB : DocumentAccess::SELF_MAX_KB;
        $request->validate([
            'file' => ['required', 'file', 'mimes:'.DocumentAccess::MIMES, 'max:'.$max],
            'issue_date' => ['nullable', 'date'],
            'expiry_date' => ['nullable', 'date', 'after_or_equal:issue_date'],
        ]);

        DB::transaction(function () use ($request, $employeeDocument, $user) {
            EmployeeDocumentVersion::create([
                'employee_document_id' => $employeeDocument->id,
                'version' => $employeeDocument->version,
                'file_path' => $employeeDocument->file_path,
                'file_name' => $employeeDocument->file_name,
                'mime_type' => $employeeDocument->mime_type,
                'file_size' => $employeeDocument->file_size,
                'uploaded_by' => $employeeDocument->uploaded_by,
                'uploaded_at' => $employeeDocument->updated_at ?? $employeeDocument->created_at,
            ]);
            $file = DocumentAccess::store($request->file('file'), "documents/employees/{$employeeDocument->employee_id}");
            $changes = [...$file, 'version' => $employeeDocument->version + 1, 'uploaded_by' => $user->id];
            if ($request->filled('issue_date')) {
                $changes['issue_date'] = $request->date('issue_date');
            }
            if ($request->filled('expiry_date')) {
                $changes += ['expiry_date' => $request->date('expiry_date'), 'alert_30_sent_at' => null, 'alert_7_sent_at' => null];
            }
            $employeeDocument->update($changes);
        });

        return response()->json($this->present($employeeDocument->fresh(['type:id,name,group', 'uploader:id,name']), $user));
    }

    public function destroy(Request $request, EmployeeDocument $employeeDocument): JsonResponse
    {
        abort_unless(DocumentAccess::canModify($request->user(), $employeeDocument), 403);
        $employeeDocument->delete(); // soft delete: the file is kept for audit

        return response()->json(['message' => 'Document deleted.']);
    }

    public function download(Request $request, EmployeeDocument $employeeDocument): StreamedResponse
    {
        abort_unless(DocumentAccess::canView($request->user(), $employeeDocument), 403);
        $file = $employeeDocument;
        if ($request->filled('version')) {
            $file = $employeeDocument->versions()->whereKey($request->integer('version'))->firstOrFail();
        }
        activity('documents')->performedOn($employeeDocument)->causedBy($request->user())
            ->withProperties(['inline' => $request->boolean('inline'), 'version' => $file->version])
            ->event('downloaded')->log('Document viewed');

        return DocumentAccess::respond($file->file_path, $file->file_name, $file->mime_type, $request->boolean('inline'));
    }

    /** HR: documents expiring (or expired) in the next N days. */
    public function expiring(Request $request): JsonResponse
    {
        $days = min(max($request->integer('days', 60), 1), 365);
        $docs = EmployeeDocument::query()
            ->whereNotNull('expiry_date')
            ->where('expiry_date', '<=', today()->addDays($days)->toDateString())
            ->when(! $request->boolean('include_expired', true), fn ($q) => $q->where('expiry_date', '>=', today()->toDateString()))
            ->whereHas('employee', fn ($q) => $q->where('status', 'active'))
            ->with(['type:id,name', 'employee:id,first_name,last_name,employee_number,department_id,photo_path', 'employee.department:id,name'])
            ->orderBy('expiry_date')
            ->limit(500)
            ->get()
            ->map(fn (EmployeeDocument $d) => [
                ...$this->present($d, $request->user()),
                'employee' => ['id' => $d->employee->id, 'full_name' => $d->employee->full_name, 'employee_number' => $d->employee->employee_number,
                    'department' => $d->employee->department?->name, 'photo_url' => $d->employee->photo_url],
            ]);

        return response()->json(['data' => $docs]);
    }

    /** HR: per-employee file overview (counts and missing required documents). */
    public function overview(Request $request): JsonResponse
    {
        $required = DocumentType::query()->where('is_required', true)->where('is_active', true)->get(['id', 'company_id']);
        $page = Employee::query()->active()->search($request->query('search'))
            ->when($request->integer('department_id'), fn ($q, $d) => $q->where('department_id', $d))
            ->with('department:id,name')
            ->withCount(['documents' => fn ($q) => $q->whereNull('deleted_at')])
            ->orderBy('first_name')
            ->paginate(min($request->integer('per_page', 20), 100));

        $ids = collect($page->items())->pluck('id');
        $have = EmployeeDocument::query()->whereIn('employee_id', $ids)->whereNotNull('document_type_id')
            ->get(['employee_id', 'document_type_id'])->groupBy('employee_id')
            ->map(fn ($g) => $g->pluck('document_type_id')->unique()->all());

        $page->through(function (Employee $e) use ($required, $have) {
            $needed = $required->where('company_id', $e->company_id)->pluck('id');
            $missing = $needed->diff($have[$e->id] ?? [])->count();

            return [
                'id' => $e->id, 'full_name' => $e->full_name, 'employee_number' => $e->employee_number,
                'department' => $e->department?->name, 'photo_url' => $e->photo_url,
                'documents_count' => $e->documents_count, 'missing_required' => $missing, 'required_total' => $needed->count(),
            ];
        });

        return response()->json($page);
    }

    private function validated(Request $request, Employee $employee, bool $creating, bool $manages): array
    {
        $max = $manages ? DocumentAccess::HR_MAX_KB : DocumentAccess::SELF_MAX_KB;
        $typeRule = Rule::exists('document_types', 'id')->where('company_id', $employee->company_id)->where('is_active', true);
        $data = $request->validate([
            'title' => [$creating ? 'required' : 'sometimes', 'string', 'max:200'],
            'document_type_id' => [$creating ? 'required' : 'sometimes', 'nullable', 'integer', $typeRule],
            'issue_date' => ['nullable', 'date', 'before_or_equal:today'],
            'expiry_date' => ['nullable', 'date', 'after_or_equal:issue_date'],
            'notes' => ['nullable', 'string', 'max:2000'],
            'file' => [$creating ? 'required' : 'prohibited', 'file', 'mimes:'.DocumentAccess::MIMES, 'max:'.$max],
        ], [
            'file.max' => 'The file may not be larger than '.($max / 1024).' MB.',
            'file.mimes' => 'Upload a PDF, Word (DOC/DOCX), ODT, JPG or PNG file.',
        ]);

        $typeId = $data['document_type_id'] ?? null;
        if ($typeId && ($creating || array_key_exists('expiry_date', $data))) {
            $type = DocumentType::withoutGlobalScope('company')->find($typeId);
            if ($type?->requires_expiry && empty($data['expiry_date'])) {
                throw \Illuminate\Validation\ValidationException::withMessages(['expiry_date' => "An expiry date is required for {$type->name}."]);
            }
        }

        return collect($data)->except('file')->all();
    }

    /** Required document types and whether the employee has a current (non-expired) one. */
    private function checklist(Employee $employee, bool $manages): array
    {
        $types = DocumentType::withoutGlobalScope('company')->where('company_id', $employee->company_id)
            ->where('is_required', true)->where('is_active', true)->orderBy('sort_order')->get();
        $docs = EmployeeDocument::withoutGlobalScope('company')->where('employee_id', $employee->id)
            ->whereIn('document_type_id', $types->pluck('id'))
            ->when(! $manages, fn ($q) => $q->where('is_confidential', false))
            ->get()->groupBy('document_type_id');

        return $types->map(function (DocumentType $t) use ($docs) {
            $list = $docs[$t->id] ?? collect();
            $valid = $list->first(fn ($d) => ! $d->isExpired());
            $status = $valid ? 'present' : ($list->isNotEmpty() ? 'expired' : 'missing');

            return ['document_type_id' => $t->id, 'name' => $t->name, 'group' => $t->group, 'status' => $status];
        })->values()->all();
    }

    private function present(EmployeeDocument $d, $user): array
    {
        $days = $d->daysToExpiry();

        return [
            'id' => $d->id,
            'employee_id' => $d->employee_id,
            'title' => $d->title,
            'document_type_id' => $d->document_type_id,
            'type' => $d->type?->name,
            'group' => $d->type?->group,
            'source' => $d->source,
            'source_label' => $d->source === 'hr' ? 'HR Admin' : 'Self',
            'issue_date' => $d->issue_date?->toDateString(),
            'expiry_date' => $d->expiry_date?->toDateString(),
            'days_to_expiry' => $days,
            'expiry_status' => $days === null ? null : ($days < 0 ? 'expired' : ($days <= 30 ? 'expiring' : 'valid')),
            'notes' => $d->notes,
            'is_confidential' => $d->is_confidential,
            'file_name' => $d->file_name,
            'mime_type' => $d->mime_type,
            'file_size' => (int) $d->file_size,
            'size_human' => DocumentAccess::humanSize((int) $d->file_size),
            'previewable' => in_array($d->mime_type, DocumentAccess::PREVIEWABLE, true),
            'version' => $d->version,
            'versions_count' => $d->versions_count ?? null,
            'uploaded_by' => $d->uploader?->name,
            'created_at' => $d->created_at,
            'updated_at' => $d->updated_at,
            'can_modify' => DocumentAccess::canModify($user, $d),
        ];
    }
}
